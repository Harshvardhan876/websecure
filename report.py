"""Branded PDF report using fpdf (exact TRD dependency, not ReportLab)."""
import math
import os
import re
from datetime import datetime, timezone
from urllib.parse import urlparse

from fpdf import FPDF

from scanner import FIX_EXAMPLES, WEIGHTS, points_for

PAGE_W = 210
MARGIN = 15
CONTENT_W = PAGE_W - 2 * MARGIN

# Print-friendly colours: the project's muted status palette on white, and the app's teal for the brand band.
INK = (15, 23, 42)
MUTED = (71, 85, 105)
RULE = (203, 213, 225)
SOFT = (241, 245, 249)
BRAND = (11, 34, 37)
BRAND_ACCENT = (203, 214, 143)
# Rendered from static/logo.svg on the brand colour (fpdf 1.7.2 cannot read SVG or PNG transparency).
LOGO_PNG = os.path.join(os.path.dirname(os.path.abspath(__file__)), "static", "logo-pdf.png")
BRAND_TEXT = (230, 235, 227)
STATUS_COLOURS = {"PASS": (22, 101, 52), "WARNING": (133, 77, 14), "FAIL": (153, 27, 27)}
RATING_COLOURS = {"Strong": (22, 101, 52), "Moderate": (133, 77, 14), "Weak": (153, 27, 27), "Minimal": (153, 27, 27)}


def _safe(text):
    """fpdf 1.7.2 only supports Latin-1 output."""
    return str(text).encode("latin-1", "replace").decode("latin-1")


def report_filename(scan):
    host = re.sub(r"[^a-z0-9.-]", "", (urlparse(scan.target_url).hostname or "site").lower()) or "site"
    return f"WebSecure-report-{host}-{scan.scan_date.strftime('%Y-%m-%d')}.pdf"


class ReportPDF(FPDF):
    def header(self):
        self.set_fill_color(*BRAND)
        self.rect(0, 0, PAGE_W, 20, "F")
        self.image(LOGO_PNG, MARGIN, 3.5, h=13)
        # Two-tone wordmark, as on the website: "Web" light, "Secure" sage.
        self.set_font("Helvetica", "B", 15)
        self.set_xy(MARGIN + 13, 6)
        self.set_text_color(*BRAND_TEXT)
        self.cell(self.get_string_width("Web"), 8, "Web")
        self.set_text_color(*BRAND_ACCENT)
        self.cell(40, 8, "Secure")
        self.set_xy(PAGE_W - MARGIN - 80, 6)
        self.set_font("Helvetica", "", 9)
        self.cell(80, 8, "Security Header Report", align="R")
        self.set_y(28)

    def footer(self):
        self.set_y(-14)
        self.set_draw_color(*RULE)
        self.line(MARGIN, self.get_y(), PAGE_W - MARGIN, self.get_y())
        self.set_y(-11)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*MUTED)
        self.cell(CONTENT_W / 2, 6, _safe("Generated by WebSecure \xb7 websecure.live"))
        self.cell(CONTENT_W / 2, 6, f"Page {self.page_no()} of {{nb}}", align="R")

    def lines_needed(self, text, width, font_size):
        """Rough line count for multi_cell, used to keep a finding's block on one page."""
        self.set_font_size(font_size)
        total = 0
        for paragraph in str(text).split("\n"):
            total += max(1, math.ceil(self.get_string_width(_safe(paragraph)) / (width - 2)))
        return total

    def keep_together(self, height):
        if self.get_y() + height > self.page_break_trigger:
            self.add_page()


def _heading(pdf, text):
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(*INK)
    pdf.cell(CONTENT_W, 8, _safe(text), ln=1)
    pdf.set_draw_color(*RULE)
    pdf.line(MARGIN, pdf.get_y(), PAGE_W - MARGIN, pdf.get_y())
    pdf.ln(3)


def _summary(pdf, scan):
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(*INK)
    pdf.cell(CONTENT_W, 9, "Security header report", ln=1)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*MUTED)
    pdf.multi_cell(CONTENT_W, 5, _safe(f"Target: {scan.target_url}"))
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    pdf.cell(CONTENT_W, 5, _safe(f"Scanned: {scan.scan_date.strftime('%Y-%m-%d %H:%M UTC')}   \xb7   Report generated: {generated}"), ln=1)
    pdf.ln(4)

    statuses = [f.status for f in scan.findings if f.header_name in WEIGHTS]
    rating_colour = RATING_COLOURS.get(scan.risk_level, INK)
    top = pdf.get_y()
    boxes = [
        ("Score", f"{scan.security_score}/100", INK),
        ("Header hardening", scan.risk_level, rating_colour),
        ("Passed / Warnings / Failed", f"{statuses.count('PASS')} / {statuses.count('WARNING')} / {statuses.count('FAIL')}", INK),
    ]
    box_w = (CONTENT_W - 8) / 3
    for i, (label, value, colour) in enumerate(boxes):
        x = MARGIN + i * (box_w + 4)
        pdf.set_fill_color(*SOFT)
        pdf.set_draw_color(*RULE)
        pdf.rect(x, top, box_w, 22, "DF")
        pdf.set_xy(x + 4, top + 3)
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(*MUTED)
        pdf.cell(box_w - 8, 5, _safe(label.upper()))
        pdf.set_xy(x + 4, top + 10)
        pdf.set_font("Helvetica", "B", 16)
        pdf.set_text_color(*colour)
        pdf.cell(box_w - 8, 9, _safe(value))
    pdf.set_y(top + 27)

    # Score bar
    pdf.set_fill_color(*RULE)
    pdf.rect(MARGIN, pdf.get_y(), CONTENT_W, 3, "F")
    pdf.set_fill_color(*rating_colour)
    pdf.rect(MARGIN, pdf.get_y(), CONTENT_W * scan.security_score / 100, 3, "F")
    pdf.ln(7)

    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(*MUTED)
    pdf.multi_cell(CONTENT_W, 4.5, align="L", txt=_safe(
        "This score rates the security headers of this one page. It is not a full security audit "
        "and does not mean the site is vulnerable. A missing header is a hardening finding."
    ))


def _breakdown(pdf, scan):
    _heading(pdf, "How the score was calculated")
    widths = (90, 30, 30, 30)
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(*MUTED)
    pdf.set_fill_color(*SOFT)
    for label, w, align in zip(("Check", "Weight", "Result", "Points"), widths, "LCCC"):
        pdf.cell(w, 7, label, border="B", align=align, fill=True)
    pdf.ln()
    pdf.set_font("Helvetica", "", 9)
    for f in scan.findings:
        points = points_for(f.header_name, f.status)
        if points is None:
            continue
        pdf.set_text_color(*INK)
        pdf.cell(widths[0], 6.5, _safe(f.header_name), border="B")
        pdf.cell(widths[1], 6.5, str(WEIGHTS[f.header_name]), border="B", align="C")
        pdf.set_text_color(*STATUS_COLOURS.get(f.status, INK))
        pdf.set_font("Helvetica", "B", 9)
        pdf.cell(widths[2], 6.5, _safe(f.status), border="B", align="C")
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(*INK)
        pdf.cell(widths[3], 6.5, str(points), border="B", align="C", ln=1)
    pdf.set_font("Helvetica", "B", 9)
    pdf.cell(sum(widths[:3]), 7, "Total", align="R")
    pdf.cell(widths[3], 7, f"{scan.security_score} / 100", align="C", ln=1)
    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(*MUTED)
    pdf.cell(CONTENT_W, 5, "PASS earns the full weight, WARNING half (rounded down), FAIL nothing.", ln=1)


def _finding(pdf, f):
    fix = FIX_EXAMPLES.get(f.header_name) if f.status != "PASS" else None
    text_w = CONTENT_W - 6
    height = 9 + 4.6 * pdf.lines_needed(f.description, text_w, 9) + 4.6 * pdf.lines_needed(f"Recommendation: {f.recommendation}", text_w, 9)
    if fix:
        height += 6 + 4.2 * pdf.lines_needed(fix, text_w - 4, 8)
    pdf.keep_together(height + 6)

    top = pdf.get_y()
    pdf.set_draw_color(*RULE)
    pdf.line(MARGIN, top - 2.5, PAGE_W - MARGIN, top - 2.5)
    pdf.set_fill_color(*STATUS_COLOURS.get(f.status, (30, 58, 138)))

    pdf.set_xy(MARGIN + 4, top)
    pdf.set_font("Helvetica", "B", 10.5)
    pdf.set_text_color(*INK)
    pdf.cell(text_w - 50, 6, _safe(f.header_name))
    badge = _safe(f.status)
    pdf.set_font("Helvetica", "B", 8)
    badge_w = pdf.get_string_width(badge) + 6
    pdf.set_text_color(255, 255, 255)
    pdf.set_xy(PAGE_W - MARGIN - badge_w - 22, top + 0.8)
    pdf.cell(badge_w, 4.6, badge, align="C", fill=True)
    pdf.set_text_color(*MUTED)
    pdf.set_font("Helvetica", "", 8)
    pdf.cell(22, 4.6, _safe(f.severity), align="R")

    pdf.set_xy(MARGIN + 4, top + 7)
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*INK)
    pdf.multi_cell(text_w, 4.6, _safe(f.description), align="L")
    pdf.set_x(MARGIN + 4)
    pdf.set_text_color(*MUTED)
    pdf.multi_cell(text_w, 4.6, _safe(f"Recommendation: {f.recommendation}"), align="L")
    if fix:
        pdf.ln(1.5)
        pdf.set_x(MARGIN + 4)
        pdf.set_font("Helvetica", "B", 8)
        pdf.set_text_color(*MUTED)
        pdf.cell(text_w, 4, "Example fix", ln=1)
        pdf.set_x(MARGIN + 4)
        pdf.set_fill_color(*SOFT)
        pdf.set_font("Courier", "", 8)
        pdf.set_text_color(*INK)
        pdf.multi_cell(text_w, 4.2, _safe(fix), fill=True, align="L")
    pdf.set_y(pdf.get_y() + 5)


def build_report_pdf(scan):
    pdf = ReportPDF(format="A4")
    pdf.set_title(_safe(f"WebSecure report - {scan.target_url}"))
    pdf.set_author("WebSecure")
    pdf.set_creator("WebSecure (websecure.live)")
    pdf.set_margins(MARGIN, 28, MARGIN)
    pdf.set_auto_page_break(True, margin=20)
    pdf.alias_nb_pages()
    pdf.add_page()

    _summary(pdf, scan)
    _breakdown(pdf, scan)
    _heading(pdf, "Findings")
    order = {"FAIL": 0, "WARNING": 1, "PASS": 2}
    for f in sorted(scan.findings, key=lambda f: order.get(f.status, 1)):
        _finding(pdf, f)

    return bytes(pdf.output(dest="S").encode("latin-1"))
